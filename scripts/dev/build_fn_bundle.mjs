// CHANGE 2026-11-13 F23-DEV-02: new file (no previous version).
// Builds the file that is DEPLOYED as `request-trip/index.ts`: one self-contained module made from
//   _shared/countries.ts + _shared/approve.ts + the library part of invite-manager/index.ts (everything except its HTTP
//   handler, store and server) + request-trip/index.ts — comments and types removed (TypeScript transpile), each source
//   module wrapped in its own scope so no name can collide. Reason: the Supabase Connector takes the function's files
//   inline, and the full sources are ~105 KB; the bundle is ~55 KB and needs no file outside request-trip/.
//   The deploy is: request-trip/main.ts (as in the repo) + request-trip/index.ts (= this bundle).
// usage: node scripts/dev/build_fn_bundle.mjs [--check]     output: supabase/functions/request-trip/deploy.bundle.ts
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const ts = createRequire(import.meta.url)("typescript");
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const FN = join(ROOT, "supabase", "functions");
const OUT = join(FN, "request-trip", "deploy.bundle.ts");
const IM_DROP = new Set(["makeHandler", "supabaseStore", "startServer", "COLS", "renderRejectEmail", "REJECT_TEXT", "cleanDraftName", "makeToken"]);   // invite-manager: HTTP side and helpers request-trip does not use

function stmtNames(st) {
  if (ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st)) return st.name ? [st.name.text] : [];
  if (ts.isVariableStatement(st)) return st.declarationList.declarations.map((d) => (ts.isIdentifier(d.name) ? d.name.text : ""));
  return [];
}
function load(rel, drop) {
  let src = readFileSync(join(FN, rel), "utf8");
  if (drop) {
    const sf = ts.createSourceFile(rel, src, ts.ScriptTarget.ES2022, true);
    let out = "";
    for (const st of sf.statements) if (!stmtNames(st).some((n) => drop.has(n))) out += src.slice(st.getFullStart(), st.getEnd());
    src = out;
  }
  // the sources end with `if (import.meta.main) startServer();` — in the bundle only request-trip/main.ts starts the server
  src = src.replace(/^if \(import\.meta\.main\)\s*startServer\(\);[ \t]*$/m, "");
  let js = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: true, newLine: ts.NewLineKind.LineFeed } }).outputText;
  const npm = [], rels = [];
  js = js.replace(/^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";?[ \t]*\n/gm, (_, names, from) => {
    (from.startsWith("npm:") ? npm : rels).push({ names: names.split(",").map((s) => s.trim()).filter(Boolean), from });
    return "";
  });
  if (/^import\s/m.test(js)) throw new Error(rel + ": an import form this script does not handle");
  const exports = [];
  js = js.replace(/^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kind, name) => { exports.push(name); return kind + " " + name; });
  if (/^export\s/m.test(js)) throw new Error(rel + ": an export form this script does not handle");
  return { rel, js: js.trim(), npm, rels, exports };
}
const MODS = [
  { id: "__countries", rel: "_shared/countries.ts" },
  { id: "__approve", rel: "_shared/approve.ts" },
  { id: "__im", rel: "invite-manager/index.ts", drop: IM_DROP },
  { id: "__rt", rel: "request-trip/index.ts" },
];
const byFile = { "countries.ts": "__countries", "approve.ts": "__approve", "invite-manager/index.ts": "__im" };
const idOf = (from) => { for (const k in byFile) if (from.endsWith(k)) return byFile[k]; throw new Error("unknown relative import " + from); };
const loaded = MODS.map((m) => ({ ...m, ...load(m.rel, m.drop || new Set()) }));
const version = (/export const FN_VERSION = "([^"]+)"/.exec(readFileSync(join(FN, "request-trip", "index.ts"), "utf8")) || [])[1];
const npmNames = new Map();
for (const m of loaded) for (const i of m.npm) for (const n of i.names) npmNames.set(n, i.from);
let out = `// Lonely Planner Edge Function \`request-trip\` · DEPLOY BUNDLE · version ${version} · F23\n` +
  "// GENERATED by scripts/dev/build_fn_bundle.mjs — do not edit. Sources (the files to read and change):\n" +
  "//   supabase/functions/_shared/countries.ts, _shared/approve.ts, invite-manager/index.ts (library part), request-trip/index.ts.\n" +
  "// Deployed as request-trip/index.ts next to request-trip/main.ts. Comments and types are removed; the code is the same.\n";
const froms = [...new Set(npmNames.values())];
for (const f of froms) out += `import { ${[...npmNames].filter(([, v]) => v === f).map(([k]) => k).join(", ")} } from "${f}";\n`;
for (const m of loaded) {
  const used = m.id === "__im" ? [] : m.rels;   // the library part of invite-manager uses nothing from the shared module
  out += `const ${m.id} = (() => {\n` + used.map((i) => `const { ${i.names.join(", ")} } = ${idOf(i.from)};\n`).join("") + m.js + `\nreturn { ${m.exports.join(", ")} };\n})();\n`;
}
const rt = loaded[loaded.length - 1];
out += `export const { ${rt.exports.join(", ")} } = __rt;\n`;
if (process.argv.includes("--check")) process.exit(readFileSync(OUT, "utf8") === out ? 0 : 1);
writeFileSync(OUT, out, "utf8");
console.log("wrote", OUT, out.length, "chars; exports:", rt.exports.length);
